@Suite struct ClaudeCodeSessionsTests {
    /// Lines shaped like Claude Code's transcripts (`~/.claude/projects/<key>/<id>.jsonl`).
    static func line(_ object: [String: Any]) -> String {
        String(decoding: try! JSONSerialization.data(withJSONObject: object, options: [.sortedKeys]), as: UTF8.self)
    }

    static func user(_ content: Any, cwd: String = "/Users/me/dev/kite", branch: String = "main", extra: [String: Any] = [:]) -> String {
        line(["type": "user", "cwd": cwd, "gitBranch": branch, "sessionId": "s", "timestamp": "2026-11-02T10:00:00.000Z",
              "message": ["role": "user", "content": content]].merging(extra) { $1 })
    }

    static func assistant(_ blocks: [[String: Any]], cwd: String = "/Users/me/dev/kite") -> String {
        line(["type": "assistant", "cwd": cwd, "gitBranch": "main", "sessionId": "s", "timestamp": "2026-11-02T10:00:05.000Z",
              "message": ["role": "assistant", "content": blocks]])
    }

    static let sample = [
        line(["type": "summary", "summary": "Fix the sidebar resize cursor", "leafUuid": "x"]),
        user("<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>"),
        user("Caveat: The messages below were generated by the user while running local commands.", extra: ["isMeta": true]),
        user("the resize cursor flickers when the sidebar is hidden\nsecond line"),
        assistant([["type": "text", "text": "Looking at it."],
                   ["type": "tool_use", "id": "t1", "name": "Bash", "input": ["command": "swift build\n--quiet"]]]),
        user([["type": "tool_result", "tool_use_id": "t1", "is_error": true, "content": "error: no such module\nmore"]]),
        assistant([["type": "tool_use", "id": "t2", "name": "Edit", "input": ["file_path": "/Users/me/dev/kite/Sources/A.swift"]]]),
        user([["type": "tool_result", "tool_use_id": "t2", "content": "ok"]]),
        assistant([["type": "text", "text": "Subagent work"]]).replacingOccurrences(of: "\"type\":\"assistant\"", with: "\"isSidechain\":true,\"type\":\"assistant\""),
        assistant([["type": "text", "text": "Fixed: the zone is off while hidden."]]),
        user("[Request interrupted by user]"),
    ].joined(separator: "\n")

    @Test func readsTheConversation() {
        let entries = ClaudeCodeTranscript.entries(Data(Self.sample.utf8))
        #expect(entries.map(\.kind) == [.note, .user, .assistant, .tool, .toolError, .tool, .assistant, .note])
        #expect(entries[0].text == "/clear")
        #expect(entries[1].text == "the resize cursor flickers when the sidebar is hidden\nsecond line")
        #expect(entries[3].text == "Bash · swift build")
        #expect(entries[4].text == "error: no such module")
        #expect(entries[5].text == "Edit · A.swift")
        #expect(entries[6].text == "Fixed: the zone is off while hidden.")
    }

    @Test func titlesTheSession() {
        let data = Data(Self.sample.utf8)
        let info = ClaudeCodeTranscript.info(head: data)
        #expect(info?.title == "Fix the sidebar resize cursor")
        #expect(info?.directory == "/Users/me/dev/kite")
        #expect(info?.gitBranch == "main")

        // No summary: the first thing the user asked, its first line.
        let plain = [Self.user("<command-name>/clear</command-name>"), Self.user("make ⌘J faster\nplease")].joined(separator: "\n")
        #expect(ClaudeCodeTranscript.info(head: Data(plain.utf8))?.title == "make ⌘J faster")

        // Claude Code's own title beats the first prompt.
        let titled = plain + "\n" + Self.line(["type": "ai-title", "aiTitle": "Faster ⌘J", "sessionId": "s"])
        #expect(ClaudeCodeTranscript.info(head: Data(titled.utf8))?.title == "Faster ⌘J")

        // A name the user gave wins, wherever it is.
        let renamed = plain + "\n" + Self.line(["type": "custom-title", "customTitle": "Speed up ⌘J", "sessionId": "s"])
        #expect(ClaudeCodeTranscript.info(head: Data(renamed.utf8))?.title == "Speed up ⌘J")

        // Nothing the user said: not a session to list.
        #expect(ClaudeCodeTranscript.info(head: Data(Self.line(["type": "summary"]).utf8)) == nil)

        // The tail's first line may be cut mid-JSON; the folder it moved to still counts.
        let tail = Data(("…cut\"}\n" + Self.user("next", cwd: "/Users/me/dev/kite/sub", branch: "feature")).utf8)
        let both = ClaudeCodeTranscript.info(head: Data(plain.utf8), tail: tail)
        #expect(both?.directory == "/Users/me/dev/kite/sub")
        #expect(both?.gitBranch == "feature")
        #expect(both?.title == "make ⌘J faster")
    }

    @Test func listsPinnedThenRecent() throws {
        #if !os(Windows)
        let files = FileManager.default
        let home = files.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? files.removeItem(at: home) }
        let projects = ClaudeCodeSessions.projectsDirectory(home: home)
        func write(_ id: String, folder: String, cwd: String, prompt: String, age: TimeInterval) throws {
            let dir = projects.appendingPathComponent(folder)
            try files.createDirectory(at: dir, withIntermediateDirectories: true)
            let file = dir.appendingPathComponent("\(id).jsonl")
            try Data(Self.user(prompt, cwd: cwd).utf8).write(to: file)
            try files.setAttributes([.modificationDate: Date().addingTimeInterval(-age)], ofItemAtPath: file.path)
        }
        let ids = (0..<8).map { _ in UUID().uuidString.lowercased() }
        for (i, id) in ids.enumerated() {
            try write(id, folder: "-Users-me-dev-kite", cwd: "/Users/me/dev/kite", prompt: "task \(i)", age: Double(i) * 60)
        }
        // Kite's own ⌘J tasks, a subagent's file and a non-transcript aren't listed.
        try write(UUID().uuidString, folder: "-Kite-Claude-Work", cwd: "/Kite/Claude/Work", prompt: "kite task", age: 0)
        try write("agent-1234", folder: "-Users-me-dev-kite", cwd: "/Users/me/dev/kite", prompt: "sub", age: 0)

        let list = ClaudeCodeSessions.list(home: home, pinned: [ids[6], "gone"], limit: 5, excluding: ["/Kite/Claude"])
        #expect(list.pinned.map(\.id) == [ids[6]])
        #expect(list.recent.map(\.id) == Array(ids[0..<5]))
        #expect(list.recent.first?.title == "task 0")
        #expect(list.recent.first?.isLive() == true)
        #expect(list.recent.last?.isLive() == false)
        #expect(ClaudeCodeSessions.transcript(id: ids[7], home: home)?.lastPathComponent == "\(ids[7]).jsonl")
        // The shown session stays readable once it's off the list.
        #expect(ClaudeCodeSessions.list(home: home, pinned: [], limit: 5, shown: ids[7]).shown?.title == "task 7")
        #expect(ClaudeCodeSessions.list(home: home, pinned: [], limit: 5).shown == nil)
        #endif
    }

    @Test func followsAGrowingTranscript() throws {
        let file = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString + ".jsonl")
        defer { try? FileManager.default.removeItem(at: file) }
        try Data((Self.user("first") + "\n" + Self.assistant([["type": "text", "text": "one"]]) + "\n").utf8).write(to: file)
        var reader = ClaudeCodeTranscriptReader()
        do { let changed = reader.read(file); #expect(changed) }
        #expect(reader.entries.map(\.text) == ["first", "one"])
        do { let changed = reader.read(file); #expect(!changed) }

        // A line still being written waits for its newline.
        let handle = try FileHandle(forWritingTo: file)
        try handle.seekToEnd()
        let next = Self.user("second")
        try handle.write(contentsOf: Data(next.prefix(20).utf8))
        do { let changed = reader.read(file); #expect(!changed) }
        try handle.write(contentsOf: Data((next.dropFirst(20) + "\n").utf8))
        try handle.close()
        do { let changed = reader.read(file); #expect(changed) }
        #expect(reader.entries.map(\.text) == ["first", "one", "second"])

        // A big file starts near its end; the cut line there is skipped.
        var tail = ClaudeCodeTranscriptReader()
        do { let changed = tail.read(file, startBytes: 10); #expect(!changed) }
        #expect(tail.entries.map(\.text) == [])
        var last = ClaudeCodeTranscriptReader()
        do { let changed = last.read(file, startBytes: UInt64(next.utf8.count + 1)); #expect(changed) }
        #expect(last.entries.map(\.text) == ["second"])
    }

    @Test func readsTheClaudeAppsTitles() throws {
        #if !os(Windows)
        let files = FileManager.default
        let home = files.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? files.removeItem(at: home) }
        let cli = UUID().uuidString.lowercased(), archived = UUID().uuidString.lowercased()
        let dir = projectsDir(home).appendingPathComponent("-Users-me-dev-kite")
        try files.createDirectory(at: dir, withIntermediateDirectories: true)
        for id in [cli, archived] {
            try Data(Self.user("the first prompt").utf8).write(to: dir.appendingPathComponent("\(id).jsonl"))
        }
        let org = ClaudeDesktopSessions.directory(home: home).appendingPathComponent("acct/org")
        try files.createDirectory(at: org, withIntermediateDirectories: true)
        func meta(_ name: String, _ object: [String: Any]) throws {
            try JSONSerialization.data(withJSONObject: object).write(to: org.appendingPathComponent(name))
        }
        try meta("local_1.json", ["sessionId": "local_1", "cliSessionId": cli, "title": "Fix the cursor", "isArchived": false])
        try meta("local_2.json", ["sessionId": "local_2", "cliSessionId": archived, "title": "Old", "isArchived": true])
        try meta("local_3.json", ["sessionId": "local_3", "title": ""])
        try Data("not json".utf8).write(to: org.appendingPathComponent("local_4.json"))

        let index = ClaudeDesktopSessions.index(home: home)
        #expect(index.byCLISessionID[cli] == ClaudeDesktopSession(title: "Fix the cursor", isArchived: false))
        #expect(index.byCLISessionID.count == 2)
        // An unchanged file isn't read again.
        #expect(ClaudeDesktopSessions.index(home: home, previous: index).byCLISessionID == index.byCLISessionID)

        let list = ClaudeCodeSessions.list(home: home, pinned: [archived], desktop: index.byCLISessionID)
        #expect(list.recent.map(\.title) == ["Fix the cursor"])
        // Archived in the app: not recent, but still shown when pinned.
        #expect(list.pinned.map(\.title) == ["Old"])
        #endif
    }

    private func projectsDir(_ home: URL) -> URL { ClaudeCodeSessions.projectsDirectory(home: home) }

    @Test func pinsSurviveAndFollowRenames() throws {
        var pins = ClaudeCodePins()
        pins.toggle("a")
        pins.toggle("b")
        pins.toggle("a")
        #expect(pins.pinned == ["b"])
        pins.rename("b", to: "c")
        #expect(pins.pinned == ["c"])
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString).appendingPathComponent("code-sessions.json")
        try pins.save(to: url)
        #expect(ClaudeCodePins.load(from: url) == pins)
    }

    @Test func runsTheUsersOwnClaudeCode() {
        let resume = ClaudeCodeInvocation.arguments(resume: "abc", permissions: .acceptEdits)
        #expect(resume.contains("--resume") && resume.last == "abc")
        #expect(resume.contains("acceptEdits"))
        // Unlike ⌘J tasks: the user's own tools and MCP servers, not Kite's alone.
        #expect(!resume.contains("--strict-mcp-config") && !resume.contains("--tools"))
        let new = ClaudeCodeInvocation.arguments(resume: nil, newSession: "id1", permissions: .bypassPermissions)
        #expect(Array(new.suffix(2)) == ["--session-id", "id1"])
        #expect(new.contains("bypassPermissions"))
    }

    @Test func testProfilesNeverReadTheUsersHome() {
        let user = URL(fileURLWithPath: "/Users/me", isDirectory: true)
        #expect(ClaudeCodeSessions.home(environment: [:], userHome: user) == user)
        // KITE_TEST_CLAUDE_HOME counts only on a test profile.
        #expect(ClaudeCodeSessions.home(environment: ["KITE_TEST_CLAUDE_HOME": "/tmp/fixture"], userHome: user) == user)
        #expect(ClaudeCodeSessions.home(environment: ["KITE_SUPPORT_PATH": "/tmp/k.1", "KITE_TEST_CLAUDE_HOME": "/tmp/fixture"],
                                        userHome: user).path == "/tmp/fixture")
        #expect(ClaudeCodeSessions.home(environment: ["KITE_SUPPORT_PATH": "/tmp/k.1"], userHome: user).path == "/tmp/k.1")
    }

