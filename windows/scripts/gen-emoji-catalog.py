#!/usr/bin/env python3
"""Writes src/core/EmojiCatalog.inc: the icon picker's emoji, by category, as the Mac's
EmojiCatalog.categories lists them (Sources/KiteMac/Views/SpaceIconPicker.swift, read here so
the two can't drift), and the Unicode name of every code point in them, for search (the Mac's
EmojiCatalog.name, which asks ICU's Any-Name transform; Windows' core has no ICU).

    py windows/scripts/gen-emoji-catalog.py      (python3 off Windows)

Names never change once Unicode assigns them, so any Python whose unicodedata knows every code
point here gives the Mac's names; the script refuses to run when one is missing, and records the
version it used.
"""
import pathlib
import re
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Sources" / "KiteMac" / "Views" / "SpaceIconPicker.swift"
OUT = ROOT / "windows" / "src" / "core" / "EmojiCatalog.inc"


def main():
    text = SOURCE.read_text(encoding="utf-8")
    categories = re.findall(r'Category\(name: "([^"]+)", symbol: "([^"]+)", emoji: chars\("([^"]*)"\)\)', text)
    if len(categories) != 8:
        sys.exit(f"expected the Mac's 8 categories, found {len(categories)}")
    points = sorted({ord(c) for _, _, emoji in categories for c in emoji})
    names = {}
    for cp in points:
        name = unicodedata.name(chr(cp), None)
        if name is None:
            sys.exit(f"Unicode {unicodedata.unidata_version} has no name for U+{cp:04X}: use a newer Python")
        names[cp] = name
    lines = [
        "// Generated by windows/scripts/gen-emoji-catalog.py from the Mac's EmojiCatalog.categories",
        f"// (Sources/KiteMac/Views/SpaceIconPicker.swift), with Unicode {unicodedata.unidata_version} names. Don't edit.",
        "// Included by core/SpaceIconPicker.cpp inside namespace kite.",
        "",
        "// Each category's name, its SF Symbol (the category bar's) and its emoji as one string, which",
        "// the Mac splits into Characters (chars).",
        "inline constexpr EmojiCategorySource kEmojiCategorySources[] = {",
    ]
    for name, symbol, emoji in categories:
        lines.append(f'    {{"{name}", "{symbol}", "{emoji}"}},')
    lines += ["};", "", "// Every code point in them and its Unicode name, by code point.", "inline constexpr CodePointName kEmojiCodePointNames[] = {"]
    for cp in points:
        lines.append(f'    {{0x{cp:X}, "{names[cp]}"}},')
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(points)} code points)")


if __name__ == "__main__":
    main()
