#!/usr/bin/env python3
"""Writes src/core/UnicodeTables.inc: code point ranges for Unicode's Letter (L*), Number (N*)
and Mark (M*) general categories, which URL input needs to classify text the way Swift's
Character.isLetter / isNumber do, without ICU or any other library.

    python3 windows/scripts/gen-unicode-tables.py

Uses Python's unicodedata; the Unicode version is recorded in the output.
"""
import pathlib
import sys
import unicodedata


def ranges(prefix):
    out, start, prev = [], None, None
    for cp in range(sys.maxunicode + 1):
        if unicodedata.category(chr(cp)).startswith(prefix):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def table(name, rs):
    lines = [f"inline constexpr CodePointRange {name}[] = {{"]
    row = []
    for a, b in rs:
        row.append(f"{{0x{a:X}, 0x{b:X}}}")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "core" / "UnicodeTables.inc"
    parts = [
        f"// Generated by windows/scripts/gen-unicode-tables.py from Unicode {unicodedata.unidata_version}. Don't edit.",
        "// Included by core/Unicode.cpp inside namespace kite::unicode.",
        "",
        table("kLetters", ranges("L")),
        "",
        table("kNumbers", ranges("N")),
        "",
        table("kMarks", ranges("M")),
        "",
    ]
    out.write_text("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
